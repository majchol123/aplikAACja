"""Offline builder for the self-hosted Piper TTS assets Worker (workers/tts).

Packages the WASM runtimes from node_modules alongside chunked Polish Piper ONNX voice
models (< 25 MiB per Cloudflare static asset limit) and emits a content-addressed manifest.
"""

from __future__ import annotations

import hashlib
import json
import logging
import shutil
import tomllib
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from .arasaac import http_get
from .symbolset import canonical_json, hash8

log = logging.getLogger(__name__)

DEFAULT_VOICES_TOML = Path(__file__).parents[1] / "tts" / "voices.toml"
TTS_DIR = Path("tts")
MARKER = ".aplikaacja-tts"
# Cloudflare Workers Static Assets cap files at 25 MiB; 16 MiB leaves plenty of headroom.
CHUNK_BYTES = 16 * 1024 * 1024

HEADERS_FILE = """\
/tts/*
  X-Content-Type-Options: nosniff
  Cross-Origin-Resource-Policy: same-origin
  Cross-Origin-Embedder-Policy: require-corp
  X-Robots-Tag: noindex
/tts/manifest.json
  Cache-Control: no-cache
/tts/runtime/*
  Cache-Control: public, max-age=31536000, immutable
/tts/voices/*
  Cache-Control: public, max-age=31536000, immutable
"""

Fetch = Callable[[str], bytes]


@dataclass(frozen=True)
class VoiceSpec:
    id: str
    name: str
    gender: str
    quality: str
    license: str
    source_name: str
    onnx_url: str
    config_url: str


def load_voice_specs(path: Path = DEFAULT_VOICES_TOML) -> list[VoiceSpec]:
    data = tomllib.loads(path.read_text("utf-8"))
    specs: list[VoiceSpec] = []
    for entry in data["voices"]:
        specs.append(
            VoiceSpec(
                id=entry["id"],
                name=entry["name"],
                gender=entry["gender"],
                quality=entry["quality"],
                license=entry["license"],
                source_name=entry["source_name"],
                onnx_url=entry["onnx_url"],
                config_url=entry["config_url"],
            )
        )
    return specs


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def prepare_out_dir(out: Path) -> Path:
    """Recreate the output directory; refuses to wipe anything it did not create."""
    if out.exists():
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise SystemExit(f"{out} is not empty and has no {MARKER} marker; refusing to delete")
        shutil.rmtree(out)
    tts_dir = out / TTS_DIR
    (tts_dir / "voices").mkdir(parents=True)
    (out / MARKER).write_text("generated by tools/build_tts.py\n", "utf-8")
    (out / ".assetsignore").write_text(f"{MARKER}\n", "utf-8")
    (out / "_headers").write_text(HEADERS_FILE, "utf-8")
    return tts_dir


def _cached_download(cache_dir: Path, filename: str, url: str, fetch: Fetch) -> bytes:
    cached = cache_dir / filename
    if cached.exists():
        return cached.read_bytes()
    log.info("Downloading %s", url)
    data = fetch(url)
    cache_dir.mkdir(parents=True, exist_ok=True)
    tmp = cache_dir / f"{filename}.tmp"
    tmp.write_bytes(data)
    tmp.replace(cached)
    return data


def _resolve_runtime_sources(node_modules: Path) -> dict[str, Path]:
    ort_dist = node_modules / "onnxruntime-web" / "dist"
    piper_build = node_modules / "@diffusionstudio" / "piper-wasm" / "build"
    files = {
        "ort-wasm-simd-threaded.mjs": ort_dist / "ort-wasm-simd-threaded.mjs",
        "ort-wasm-simd-threaded.wasm": ort_dist / "ort-wasm-simd-threaded.wasm",
        "piper_phonemize.wasm": piper_build / "piper_phonemize.wasm",
        "piper_phonemize.data": piper_build / "piper_phonemize.data",
    }
    missing = [str(p) for p in files.values() if not p.exists()]
    if missing:
        raise FileNotFoundError(f"Missing runtime TTS assets: {', '.join(missing)}")
    return files


def build(
    out: Path,
    cache_dir: Path,
    node_modules: Path,
    *,
    voices: list[VoiceSpec] | None = None,
    fetch: Fetch = http_get,
    chunk_bytes: int = CHUNK_BYTES,
) -> dict:
    specs = voices if voices is not None else load_voice_specs()
    runtime_sources = _resolve_runtime_sources(node_modules)
    tts_dir = prepare_out_dir(out)

    runtime_bytes = {name: path.read_bytes() for name, path in runtime_sources.items()}
    digest = hashlib.sha256()
    for name in sorted(runtime_bytes):
        digest.update(name.encode("utf-8"))
        digest.update(runtime_bytes[name])
    runtime_hash = digest.hexdigest()[:8]

    runtime_dir = tts_dir / "runtime" / runtime_hash
    runtime_dir.mkdir(parents=True)
    for name, content in runtime_bytes.items():
        (runtime_dir / name).write_bytes(content)

    runtime_meta = {
        "hash": runtime_hash,
        "ortMjs": f"runtime/{runtime_hash}/ort-wasm-simd-threaded.mjs",
        "ortWasm": f"runtime/{runtime_hash}/ort-wasm-simd-threaded.wasm",
        "phonemizeWasm": f"runtime/{runtime_hash}/piper_phonemize.wasm",
        "phonemizeData": f"runtime/{runtime_hash}/piper_phonemize.data",
        "phonemizeWasmSha256": sha256_hex(runtime_bytes["piper_phonemize.wasm"]),
        "phonemizeDataSha256": sha256_hex(runtime_bytes["piper_phonemize.data"]),
        "totalBytes": sum(len(b) for b in runtime_bytes.values()),
    }

    voice_entries: list[dict] = []
    for spec in specs:
        onnx_bytes = _cached_download(cache_dir, f"{spec.id}.onnx", spec.onnx_url, fetch)
        cfg_bytes = _cached_download(cache_dir, f"{spec.id}.onnx.json", spec.config_url, fetch)
        cfg = json.loads(cfg_bytes.decode("utf-8"))
        sample_rate = int(cfg["audio"]["sample_rate"])

        voice_hash = hash8(onnx_bytes + cfg_bytes)
        cfg_rel = f"voices/{spec.id}.{voice_hash}.onnx.json"
        (tts_dir / cfg_rel).write_bytes(cfg_bytes)

        parts: list[str] = []
        for idx, offset in enumerate(range(0, len(onnx_bytes), chunk_bytes)):
            part_rel = f"voices/{spec.id}.{voice_hash}.onnx.part{idx:02d}"
            (tts_dir / part_rel).write_bytes(onnx_bytes[offset : offset + chunk_bytes])
            parts.append(part_rel)

        voice_entries.append(
            {
                "id": spec.id,
                "name": spec.name,
                "gender": spec.gender,
                "quality": spec.quality,
                "sampleRate": sample_rate,
                "license": spec.license,
                "sourceName": spec.source_name,
                "bytes": len(onnx_bytes),
                "sha256": sha256_hex(onnx_bytes),
                "config": cfg_rel,
                "parts": parts,
            }
        )

    manifest = {"v": 1, "runtime": runtime_meta, "voices": voice_entries}
    (tts_dir / "manifest.json").write_bytes(canonical_json(manifest))
    return manifest
